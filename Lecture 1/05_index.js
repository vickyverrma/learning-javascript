// convert number into string
let age = 22;
age = age+"";

// 22 -> "22"
console.log(typeof age);

// another way of doing it
let age2 = 23;
age2 = String(age2);
console.log(typeof age2);

// convert string into number
let age3 = "23";
age3 = +age3;
console.log(typeof age3);

let age4 = "24";
age4 = Number(age4);
console.log(typeof age4);

